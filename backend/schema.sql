CREATE TABLE IF NOT EXISTS avatars (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
  name TEXT NOT NULL,
  image_url TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS subjects (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_name TEXT NOT NULL,
  img_url TEXT
);

CREATE TABLE IF NOT EXISTS users (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  profile_img INT REFERENCES avatars(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lists (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
  subject_id INT REFERENCES subjects(id) ON DELETE CASCADE NOT NULL,
  title TEXT,
  target_language TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS questions (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  list_id INT REFERENCES lists(id) ON DELETE CASCADE NOT NULL,
  answer TEXT NOT NULL,
  question TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS user_statistics (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
  list_id INT REFERENCES lists(id) ON DELETE CASCADE NOT NULL,
  correct_answers INT DEFAULT 0 NOT NULL,
  wrong_answers INT DEFAULT 0 NOT NULL,
  last_practiced TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT unique_user_list_stats UNIQUE (user_id, list_id)
);

CREATE TABLE IF NOT EXISTS practice_history (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT REFERENCES users(id) ON DELETE CASCADE NOT NULL,
  list_id INT REFERENCES lists(id) ON DELETE CASCADE NOT NULL,
  correct_answers INT DEFAULT 0 NOT NULL,
  wrong_answers INT DEFAULT 0 NOT NULL,
  practiced_at TIMESTAMPTZ DEFAULT NOW()
);
